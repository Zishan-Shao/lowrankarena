# ── Load bf16 backend values from expB.csv (real input mode, avg over tasks) ──
# SVD methods only (dense excluded) for backend memory/throughput comparisons.
# Dense values loaded separately from actual measurements when available.
_SVD_METHODS = {'svd', 'fwsvd', 'drone', 'adasvd'}

def _load_bf16_backend():
    p = os.path.join(_REPO_ROOT, 'experiments', 'results', 'expB.csv')
    if not os.path.exists(p):
        return {}, {}
    import csv as _csv2
    mem, thr = {}, {}
    dmem, dthr = {}, {}   # dense-only
    with open(p, newline='', encoding='utf-8') as f:
        for r in _csv2.DictReader(f):
            if r.get('dtype','').strip() != 'bf16':
                continue
            if r.get('input_mode','').strip() != 'real':
                continue
            b = r.get('backend','').strip()
            method = r.get('method','').strip()
            try:
                mv = float(r['peak_mem_mb']); tv = float(r['throughput_sps'])
            except (KeyError, ValueError):
                continue
            if method in _SVD_METHODS:
                mem.setdefault(b, []).append(mv)
                thr.setdefault(b, []).append(tv)
            elif method == 'dense':
                dmem.setdefault(b, []).append(mv)
                dthr.setdefault(b, []).append(tv)
    svd_out = {}
    for b in mem:
        svd_out[b] = dict(mem=round(sum(mem[b])/len(mem[b]), 1),
                          thr=round(sum(thr[b])/len(thr[b]), 1))
    dense_out = {}
    for b in dmem:
        dense_out[b] = dict(mem=round(sum(dmem[b])/len(dmem[b]), 1),
                            thr=round(sum(dthr[b])/len(dthr[b]), 1))
    return svd_out, dense_out

_BF16, _BF16_DENSE = _load_bf16_backend()
# Convenience: per-backend bf16 averages (fallback to fp32-based estimates if expB not found)
_MEM = lambda b, fb: _BF16.get(b, {}).get('mem', fb)
_THR = lambda b, fb: _BF16.get(b, {}).get('thr', fb)
# Dense bf16: use actual measurement if available; else estimate from fp32 ratio
