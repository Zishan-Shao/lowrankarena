# ── Load GLUE summary CSV (generated by collect_glue_results.py) ──────────────
def _load_glue_summary(dtype='bf16'):
    """Load glue_summary.csv, filtering to the requested dtype.
    Falls back to fp32 rows for any (method, qkv_mode, seq_len) not found in
    the requested dtype — so figures still render even if only fp32 data exists.
    """
    p = os.path.join(_REPO_ROOT, 'experiments', 'results', 'glue_summary.csv')
    if not os.path.exists(p):
        return {}
    # First pass: collect all rows by dtype
    by_dtype = {}
    with open(p, newline='', encoding='utf-8') as f:
        for r in _csv.DictReader(f):
            seq = int(r.get('seq_len', 128)) if r.get('seq_len', '') else 128
            dt  = r.get('dtype', 'fp32')   # old CSVs without dtype column → fp32
            by_dtype.setdefault(dt, {})[(r['method'], r['qkv_mode'], seq)] = r
    # Preferred dtype first, fall back to fp32
    preferred = by_dtype.get(dtype, {})
    fallback  = by_dtype.get('fp32', {})
    rows = {**fallback, **preferred}   # preferred overwrites fp32 where both exist
    return rows

_glue = _load_glue_summary()

# ── Load bf16 full-matrix stage1 scores from expA_full.csv ────────────────────
def _load_full_matrix_bf16():
    """Read expA_full.csv (bf16, naive, qkv_mode=full); return (task_scores, gavg).

    task_scores : dict[(method, task)] = metric_value  (stage1 only)
    gavg        : dict[method] = G-AVG over 8 GLUE tasks
    """
    _G8        = ['cola', 'sst2', 'mrpc', 'qqp', 'mnli', 'qnli', 'rte', 'stsb']
    _normalize = {'cola', 'stsb'}
    p = os.path.join(_REPO_ROOT, 'experiments', 'results', 'expA_full.csv')
    if not os.path.exists(p):
        return {}, {}
    task_scores = {}
    with open(p, newline='', encoding='utf-8') as f:
        for r in _csv.DictReader(f):
            if r.get('dtype', '').strip() != 'bf16':
                continue
            if r.get('backend', '').strip() != 'naive':
                continue
            if r.get('qkv_mode', '').strip() != 'full':
                continue
            task   = r.get('task', '').strip()
            method = r.get('method', '').strip()
            try:
                v = float(r['metric_value'])
            except (KeyError, ValueError):
                continue
            task_scores[(method, task)] = v   # last row wins
    gavg = {}
    for method in set(m for m, _ in task_scores):
        vals = []
        for task in _G8:
            v = task_scores.get((method, task))
            if v is None:
                break
            vals.append((v + 1) / 2 if task in _normalize else v)
        else:
            gavg[method] = round(sum(vals) / 8, 6)
    return task_scores, gavg

_fm_scores, _fm_gavg = _load_full_matrix_bf16()

def _gavg(method, qkv_mode, stage, seq_len=512):
    """Return G-AVG float, or None if missing.

    Priority:
      1. expA_fine_tune.csv bf16 computed G-AVG (per_head only)
      2. expA_full.csv bf16 computed G-AVG (full only, stage1 only)
      3. glue_summary.csv (bf16 preferred, fp32 fallback)
    """
    if qkv_mode == 'per_head':
        ft = _ft_gavg.get((method, stage))
        if ft is not None:
            return ft
    if qkv_mode == 'full' and stage == 1:
        v = _fm_gavg.get(method)
        if v is not None:
            return v
    v = _glue.get((method, qkv_mode, seq_len), {}).get(f'g_avg_s{stage}', '')
    return float(v) if v else None

def _ntasks(method, qkv_mode, stage, seq_len=512):
    """Return number of tasks that contributed to G-AVG (0 if row missing)."""
    v = _glue.get((method, qkv_mode, seq_len), {}).get(f'n_tasks_s{stage}', '')
    return int(v) if v else 0

def _task_score(method, qkv_mode, task, stage, seq_len=512):
    """Return per-task score float, or None if missing.

    Priority:
      1. glue_summary.csv (bf16 preferred, fp32 fallback)
      2. expA_fine_tune.csv (per_head only, bf16)
      3. expA_full.csv (full only, stage1 only, bf16)
    """
    v = _glue.get((method, qkv_mode, seq_len), {}).get(f'{task}_s{stage}', '')
    if v:
        return float(v)
    if qkv_mode == 'per_head':
        return _ft_scores.get((method, task, stage))
    if qkv_mode == 'full' and stage == 1:
        return _fm_scores.get((method, task))
    return None

# ── Load param counts from expA.csv (avg over all rows) ──────────────────────
def _load_param_counts():
    p = os.path.join(_REPO_ROOT, 'experiments', 'results', 'expA.csv')
    if not os.path.exists(p):
        return None, None
    import csv as _csv3
    orig, comp = [], []
    with open(p, newline='', encoding='utf-8') as f:
        for r in _csv3.DictReader(f):
            try:
                o = float(r.get('total_original_params') or '')
                c = float(r.get('total_compressed_params') or '')
                if o > 0: orig.append(o)
                if c > 0: comp.append(c)
            except ValueError:
                pass
    o_avg = sum(orig)/len(orig) if orig else None
    c_avg = sum(comp)/len(comp) if comp else None
    return o_avg, c_avg

_ORIG_PARAMS, _COMP_PARAMS = _load_param_counts()
